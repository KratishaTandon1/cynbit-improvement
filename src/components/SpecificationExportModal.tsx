import React, { useState } from 'react';
import type { ArchitecturePreset, RequirementConfig, RoiEstimate } from '../types/architect';
import { X, Copy, Check, Download, Printer, FileText } from 'lucide-react';

interface SpecificationExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  preset: ArchitecturePreset;
  config: RequirementConfig;
  roi: RoiEstimate;
}

export const SpecificationExportModal: React.FC<SpecificationExportModalProps> = ({
  isOpen,
  onClose,
  preset,
  config,
  roi,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdown = () => {
    return `# CYNBIT ARCHITECTURAL SPECIFICATION: ${preset.title.toUpperCase()}
Document ID: CYN-SPEC-${preset.id.toUpperCase()}-${Date.now().toString().slice(-6)}
Generated By: Cynbit Architect Studio
Date: ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}

---

## 1. EXECUTIVE SUMMARY & OBJECTIVE
${preset.description}

- **Target Archetype:** ${preset.category}
- **Primary Beneficiaries:** ${preset.targetAudience}
- **Projected Throughput:** ${config.monthlyOperations.toLocaleString()} operations / month
- **Projected Labor Hours Reclaimed:** ${roi.monthlyHoursSaved} hours / month
- **Projected Financial Savings:** $${roi.monthlyCostSavingsUSD.toLocaleString()} / month

---

## 2. SYSTEM TOPOLOGY & COMPONENT MATRIX
| Layer | Service / Role | Technology Stack | Latency SLA | Security Baseline |
| :--- | :--- | :--- | :--- | :--- |
${preset.nodes
  .map(
    (n, idx) =>
      `| Layer 0${idx + 1} | ${n.title} | ${n.tech} | ${n.latency} | ${n.details.security.slice(0, 40)}... |`
  )
  .join('\n')}

---

## 3. ARCHITECTURAL POLICIES & CONSTRAINTS
- **Compliance Standard:** ${config.complianceTier.toUpperCase()}
- **Multi-Agent Orchestration:** ${config.multiAgentOrchestration ? 'Active (LangGraph state supervisor)' : 'Standard (Single model)'}
- **Vector Memory Tier:** ${config.vectorRagEnabled ? 'Enabled (Hybrid Sparse/Dense Vector DB)' : 'Disabled'}
- **Target Cloud Infrastructure:** ${config.cloudModel.toUpperCase()}
- **Estimated Cloud/Token Monthly Run-Cost:** ~$${roi.estCloudCostPerMonthUSD.toLocaleString()} / month

---

## 4. SPRINT DELIVERY ROADMAP
${roi.sprints
  .map(
    (s) => `### Sprint 0${s.sprintNumber}: ${s.title} (${s.duration})
${s.deliverables.map((d) => `- [ ] ${d}`).join('\n')}
`
  )
  .join('\n')}

---
*Engineered by Cynbit Technologies • Architecting Scalable Digital Platforms & AI Automation Systems.*
*Jaipur, Rajasthan • contact@cynbit.in • https://cynbit.in*
`;
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(generateMarkdown());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadJson = () => {
    const data = {
      specVersion: '1.0.0',
      timestamp: new Date().toISOString(),
      preset,
      config,
      roi,
    };
    const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `cynbit-architecture-${preset.id}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-fadeIn">
      <div className="w-full max-w-3xl bg-[#0c1418] border border-white/10 rounded-3xl shadow-2xl flex flex-col max-h-[85vh] overflow-hidden">
        {/* Modal Top Bar */}
        <div className="p-4 bg-[#0e171b] border-b border-white/10 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <FileText className="w-4 h-4 text-[#96f1fa]" />
            <h3 className="text-sm font-bold text-white font-headline">
              Export Architecture Specification (RFC)
            </h3>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-white/10 transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content Viewer */}
        <div className="flex-1 p-6 overflow-y-auto space-y-4 font-mono text-xs text-slate-300 leading-relaxed bg-[#080d10]">
          <pre className="whitespace-pre-wrap">{generateMarkdown()}</pre>
        </div>

        {/* Action Controls */}
        <div className="p-4 bg-[#0e171b] border-t border-white/10 flex flex-wrap items-center justify-between gap-3">
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-4 py-2 rounded-xl bg-[#006067] hover:bg-[#007b83] text-white text-xs font-bold transition-all cursor-pointer"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-[#96f1fa]" />
                  <span>Copied to Clipboard</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy Markdown</span>
                </>
              )}
            </button>

            <button
              onClick={handleDownloadJson}
              className="flex items-center gap-1.5 px-4 py-2 rounded-xl bg-white/5 hover:bg-white/10 border border-white/10 text-slate-300 hover:text-white text-xs font-semibold transition-all cursor-pointer"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download JSON</span>
            </button>
          </div>

          <button
            onClick={handlePrint}
            className="flex items-center gap-1.5 px-4 py-2 rounded-xl bg-white/5 hover:bg-white/10 border border-white/10 text-slate-300 hover:text-white text-xs font-semibold transition-all cursor-pointer"
          >
            <Printer className="w-3.5 h-3.5" />
            <span>Print / Save PDF</span>
          </button>
        </div>
      </div>
    </div>
  );
};
